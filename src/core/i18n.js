let currentLocale = DEFAULT_LOCALE;
const listeners = new Set();

function normalizeLocale(loc) {
  if (!loc || typeof loc !== 'string') return DEFAULT_LOCALE;
  const l = loc.toLowerCase().trim();
  if (l.startsWith('zh')) return 'zh';
  if (l.startsWith('ar')) return 'ar';
  if (l.startsWith('en')) return 'en';
  return SUPPORTED_LOCALES.includes(l) ? l : DEFAULT_LOCALE;
}

function getLocale() {
  return currentLocale;
}

function setLocale(loc) {
  const next = normalizeLocale(loc);
  const prev = currentLocale;
  currentLocale = next;
  if (prev !== next) {
    listeners.forEach((fn) => {
      try { fn(next, prev); } catch (_) {}
    });
  }
  return currentLocale;
}

function getDirection(loc) {
  return normalizeLocale(loc || currentLocale) === 'ar' ? 'rtl' : 'ltr';
}

function getSupportedLocales() {
  return [...SUPPORTED_LOCALES];
}

function getDictionary(loc) {
  const l = normalizeLocale(loc || currentLocale);
  return DICTIONARIES[l] || DICTIONARIES[DEFAULT_LOCALE];
}

function formatString(template, params) {
  if (!params) return template;
  if (typeof params === 'object') {
    return template.replace(/\{(\w+)\}/g, (match, key) => {
      return params[key] !== undefined ? String(params[key]) : match;
    });
  }
  return template;
}

function has(key, loc) {
  if (!key) return false;
  const lang = normalizeLocale(loc || currentLocale);
  const dict = DICTIONARIES[lang] || DICTIONARIES[DEFAULT_LOCALE];
  return dict && dict[key] !== undefined;
}

function t(key, params, loc) {
  if (!key) return '';
  const lang = normalizeLocale(loc || currentLocale);
  const dict = DICTIONARIES[lang] || DICTIONARIES[DEFAULT_LOCALE];
  let res = dict[key];
  if (res === undefined) {
    // Fallback to English, then Chinese, then key itself
    res = DICTIONARIES.en[key] !== undefined
      ? DICTIONARIES.en[key]
      : (DICTIONARIES.zh[key] !== undefined ? DICTIONARIES.zh[key] : key);
  }
  return formatString(res, params);
}

function onLocaleChange(fn) {
  if (typeof fn === 'function') {
    listeners.add(fn);
    return () => listeners.delete(fn);
  }
  return () => {};
}

function translateDOM(root, loc) {
  let doc = typeof document !== 'undefined' ? document : null;
  if (root && root.nodeType === 9) {
    doc = root;
  } else if (root && root.ownerDocument) {
    doc = root.ownerDocument;
  }
  if (!doc) return;
  const lang = normalizeLocale(loc || (typeof root === 'string' ? root : currentLocale));
  const container = (root && typeof root.querySelectorAll === 'function') ? root : doc;
  if (!container || typeof container.querySelectorAll !== 'function') return;

  if (doc.documentElement) {
    doc.documentElement.lang = lang;
    doc.documentElement.dir = getDirection(lang);
  }

  // Text content
  const i18nElements = container.querySelectorAll('[data-i18n]');
  i18nElements.forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const val = t(key, null, lang);
      if (val.includes('<') && val.includes('>')) {
        el.innerHTML = val;
      } else {
        el.textContent = val;
      }
    }
  });

  // Placeholders
  const placeholderElements = container.querySelectorAll('[data-i18n-placeholder]');
  placeholderElements.forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key, null, lang);
  });

  // Titles / Tooltips
  const titleElements = container.querySelectorAll('[data-i18n-title]');
  titleElements.forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key, null, lang);
  });

    // Values (e.g. readonly inputs)
  const valueElements = container.querySelectorAll('[data-i18n-value]');
  valueElements.forEach((el) => {
    const key = el.getAttribute('data-i18n-value');
    if (key) el.value = t(key, null, lang);
  });

  // Aria labels
  const ariaElements = container.querySelectorAll('[data-i18n-aria-label]');
  ariaElements.forEach((el) => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (key) el.setAttribute('aria-label', t(key, null, lang));
  });
}

